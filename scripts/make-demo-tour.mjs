#!/usr/bin/env node
// Embeds docs/assets/deed-demo.gif (the README's recording of a demo visit) in the Worker, so the
// demo's landing page can show it without a static-assets binding. Run after re-recording the GIF
// (scripts/record-demo-gif.mjs): node scripts/make-demo-tour.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const gif = readFileSync(resolve(root, "docs/assets/deed-demo.gif"));
if (gif.subarray(0, 6).toString("latin1") !== "GIF89a") throw new Error("docs/assets/deed-demo.gif isn't a GIF89a");
writeFileSync(
  resolve(root, "src/interfaces/http/demo-tour.ts"),
  `// Generated by scripts/make-demo-tour.mjs from docs/assets/deed-demo.gif. Do not edit.\n` +
    `/** A recorded visit to the demo: a customer orders on the phone, the store prepares it, Deed live draws it. */\n` +
    `export const DEMO_TOUR_GIF_BASE64 = "${gif.toString("base64")}";\n`,
);
console.log(`wrote src/interfaces/http/demo-tour.ts (${gif.length} bytes of GIF)`);
