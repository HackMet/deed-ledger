#!/usr/bin/env python3
"""Draws the two synthetic supplier invoices a demo store's history seeds (demo-history.ts), and writes
src/infrastructure/demo-invoices.ts: each JPEG as base64, with the recorded reading the receipt reader
returns for exactly those bytes (by SHA-256). Made up: suppliers, products and costs are examples.
Run: python3 scripts/make-demo-invoices.py"""
import base64
import hashlib
import io
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SANS = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
OUT = Path(__file__).parent.parent / "src" / "infrastructure" / "demo-invoices.ts"

# Names are the demo catalog's (demo-store.ts), so every line matches a product the store sells.
INVOICES = {
    "received": {
        "supplier": "Distribuidora Ejemplo",
        "number": "F-001-0417",
        "lines": [
            ("Coca-Cola 600 ml", 24, "unidad", 1800),
            ("Agua Azul 1 L", 12, "unidad", 1200),
            ("Arroz 1 lb", 50, "libra", 1300),
            ("Galletas de soda", 20, "paquete", 800),
        ],
    },
    "pending": {
        "supplier": "Abarrotes Ejemplo",
        "number": "F-002-1188",
        "lines": [
            ("Aceite Clover 1 L", 12, "unidad", 4800),
            ("Frijoles rojos 1 lb", 25, "libra", 1700),
            ("Jabón Xtra (barra)", 10, "unidad", 1500),
        ],
    },
}


def lempiras(centavos: int) -> str:
    return f"L {centavos / 100:,.2f}"


def draw(invoice: dict) -> bytes:
    w, h = 720, 900
    paper = Image.new("RGB", (w, h), (250, 248, 242))
    d = ImageDraw.Draw(paper)
    title, body, small = ImageFont.truetype(BOLD, 30), ImageFont.truetype(SANS, 20), ImageFont.truetype(SANS, 16)
    d.text((40, 40), invoice["supplier"], font=title, fill=(30, 30, 30))
    d.text((40, 84), "Tocoa, Colón · Tel. 0000-0000 (ejemplo)", font=small, fill=(90, 90, 90))
    d.text((480, 44), "FACTURA", font=ImageFont.truetype(BOLD, 24), fill=(30, 30, 30))
    d.text((480, 80), f"No. {invoice['number']}", font=small, fill=(90, 90, 90))
    d.text((40, 130), "Cliente: Mercadito Demo", font=body, fill=(30, 30, 30))
    y = 190
    d.line([(40, y), (w - 40, y)], fill=(60, 60, 60), width=2)
    for x, label in ((40, "Cant."), (130, "Descripción"), (470, "P. unit."), (590, "Total")):
        d.text((x, y + 10), label, font=ImageFont.truetype(BOLD, 18), fill=(30, 30, 30))
    y += 44
    d.line([(40, y), (w - 40, y)], fill=(160, 160, 160), width=1)
    total = 0
    for name, qty, _unit, cost in invoice["lines"]:
        y += 14
        d.text((52, y), str(qty), font=body, fill=(30, 30, 30))
        d.text((130, y), name, font=body, fill=(30, 30, 30))
        d.text((470, y), lempiras(cost), font=body, fill=(30, 30, 30))
        d.text((590, y), lempiras(qty * cost), font=body, fill=(30, 30, 30))
        total += qty * cost
        y += 34
        d.line([(40, y), (w - 40, y)], fill=(210, 210, 210), width=1)
    y += 24
    d.text((470, y), "TOTAL", font=ImageFont.truetype(BOLD, 20), fill=(30, 30, 30))
    d.text((590, y), lempiras(total), font=ImageFont.truetype(BOLD, 20), fill=(30, 30, 30))
    d.text((40, h - 60), "Factura de ejemplo para la demostración. No es un documento real.", font=small, fill=(140, 60, 60))
    # A photo of paper on a counter: a little tilt and a darker border.
    photo = Image.new("RGB", (w + 80, h + 80), (92, 84, 76))
    photo.paste(paper.rotate(-1.2, expand=False, fillcolor=(92, 84, 76)), (40, 40))
    out = io.BytesIO()
    photo.save(out, format="JPEG", quality=72)
    return out.getvalue()


def main() -> None:
    parts = ["// Generated by scripts/make-demo-invoices.py. Do not edit.", 'import type { ReceiptRecording } from "../integrations/perception/recorded-receipt-reader";', ""]
    recordings = []
    for key, invoice in INVOICES.items():
        data = draw(invoice)
        sha = hashlib.sha256(data).hexdigest()
        reading = {
            "supplier": invoice["supplier"],
            "date": None,
            "lines": [{"name": n, "qtyMilli": q * 1000, "unit": u, "unitCostCentavos": c} for n, q, u, c in invoice["lines"]],
        }
        recordings.append({"source": "fixture", "sha256": sha, "reading": reading})
        parts.append(f"export const DEMO_INVOICE_{key.upper()}_JPEG_BASE64 = {json.dumps(base64.b64encode(data).decode())};")
    parts.append("")
    parts.append("/** The readings of the two invoices above, by the SHA-256 of their bytes. Synthetic. */")
    parts.append(f"export const DEMO_INVOICE_RECORDINGS: readonly ReceiptRecording[] = {json.dumps(recordings, ensure_ascii=False, indent=2)};")
    OUT.write_text("\n".join(parts) + "\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
