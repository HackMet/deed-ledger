#!/usr/bin/env node
// Writes src/infrastructure/demo-preset-files.ts: the demo phone's preset photo and voice note,
// as base64, so the Worker carries them without an upload step. Both files are synthetic:
// lista-pedido.jpg is drawn by a script, voz-pedido.ogg is a text-to-speech voice (es-HN-KarlaNeural, rate -10%)
// saying "Buenas, fíjese que necesito un cartón de huevos, dos libras de azúcar y una libra de arroz.
// Ahorita paso a traerlo." Run again after changing either file:   node scripts/make-demo-presets.mjs
import { readFileSync, writeFileSync } from "node:fs";

const b64 = (path) => readFileSync(new URL(path, import.meta.url)).toString("base64");
const out = `// Generated by scripts/make-demo-presets.mjs. Do not edit.
export const LISTA_JPEG_BASE64 = "${b64("./sim-media/lista-pedido.jpg")}";
export const VOZ_OGG_BASE64 = "${b64("./sim-media/voz-pedido.ogg")}";
`;
writeFileSync(new URL("../src/infrastructure/demo-preset-files.ts", import.meta.url), out);
console.log("wrote src/infrastructure/demo-preset-files.ts");
